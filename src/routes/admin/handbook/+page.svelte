				<li>用<b>該平台的訂單留言</b>把券碼發給他</li>
				<li>他在網站上自己輸入，立刻入帳</li>
			</ol>
			<p class="path-note">
				這條路刻意<strong>不需要知道買家是誰</strong> ——
