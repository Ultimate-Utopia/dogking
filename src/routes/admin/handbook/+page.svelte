<h2>五、補救：發兌換券</h2>
<div class="panel">
	<p class="lede">
		已付款但沒填代碼、或代碼對不到帳號的訂單，在預覽表格最右邊會有一顆
		<b>「開兌換券」</b>按鈕。按下去系統就會照那張訂單的金額開一張券，
		<u>並且把訂單編號記在券上</u>。

	</p>

	<ol class="steps">
		<li>
			<b>在那一列按「開兌換券」</b><br />
			面額自動換算（商品金額 × {fmt(data.rate)}），不必自己算。
		</li>
		<li>
			<b>立刻複製券碼</b><br />
			券碼會顯示在畫面上方。用該平台的<strong>訂單留言</strong>貼給買家，
			<u>不要貼在公開的地方</u> —— 券碼等同現金，誰先輸入誰拿到。
		</li>
		<li>
			<b>之後重匯，那一列會自己變成「已開兌換券」</b><br />
			券碼也會一起顯示，所以<strong>不必自己記哪幾張處理過了</strong>。
			觀眾兌換後會再變成「券已兌換」。
		</li>
	</ol>

	<div class="tip">
		<span class="tip-title">同一張訂單不會開出第二張券</span>
		<p>
			再按一次「開兌換券」只會把<b>原來那張</b>拿給你看（券碼弄丟時很好用）。
			如果那張券已經被兌換了，系統會直接擋下來，不會再開一張 ——
			否則同一筆訂單就發了兩次幣。
		</p>
	</div>

	<div class="tip">
		<span class="tip-title">觀眾事後才補填代碼也不會重複發</span>
		<p>
			有時你已經開了券，觀眾又跑去平台把代碼補填上去。下次匯入時那一列仍然是
			「已開兌換券」或「券已兌換」，<b>不會又自動發一次</b>。
		</p>
	</div>

	<p class="lede" style="margin:16px 0 0;font-size:14px">
		要開跟訂單無關的券（活動抽獎、補償之類），用下方「產生兌換券」手動開，
		那裡可以自己填面額與組數。
	</p>
</div>

