<!-- ── 主線操作 ────────────────────────────────────── -->
<h2>三、主線：匯入訂單</h2>
<div class="panel">
	<div class="tip" style="margin:0 0 16px">
		<span class="tip-title">開賣前先做一件事：在賣場加一個結帳問題</span>
		<p>
			到賣貨便賣場設定的「回饋資訊」，新增一題，題目名稱要含<b>「狗狗幣備註碼」</b>。
			觀眾結帳時就會看到這一格，系統也會優先從這一題抓碼。
			沒設的話，系統會退回去看「訂單備註」，但觀眾比較容易忘記填。
		</p>
	</div>

	<ol class="steps">
		<li>
			<b>從平台匯出訂單</b><br />
			<b>綠界</b>：商店後台匯出<b>「訂單明細」，一定要選 Excel</b>。綠界的 CSV 匯出欄位會亂序，不能用。
			匯出時會連同一個帳號的<u>其他賣場</u>一起下載，系統只會算賽場賣場「終焉狗王大賽」的訂單，其他自動略過。<br />
			<b>賣貨便</b>：Excel 或 CSV 都可以。<br />
			<u>不用刪欄位、不用轉檔、不用調整格式</u>，手機上直接下載的檔案就能用。
		</li>
		<li>
			<b>到<a href="/admin/coins">狗狗幣發放</a>，按「選擇訂單檔」</b><br />
			選完就會<strong>自動出現預覽</strong>，不必再按其他按鈕。
			系統會自動分辨是賣貨便還是綠界。綠界的代碼看<b>買家備註</b>，賣貨便看<b>「狗狗幣備註碼」那一題</b>。
			檔案裡的姓名、手機、地址會在你的手機上先拿掉，不會傳到網站。
		</li>
		<li>
			<b>按「預覽比對結果」</b><br />
			<strong>這一步不會發任何幣。</strong>它只是把結果算給你看：誰拿多少、哪幾筆有問題。
		</li>
		<li>
			<b>確認金額總數，再按確認發放</b><br />
			畫面會顯示「共 N 筆、合計 X 狗狗幣」。<u>數字對了再按。</u>
		</li>
	</ol>

	<div class="tip">
		<span class="tip-title">系統自動幫你擋掉的訂單</span>
		<p>
			<b>還沒付款</b>、<b>已取消</b>、
			<b>已被合併進其他訂單</b>的，這次都不會發。
			買家付款後，<strong>下次匯出時整份重匯就好</strong> —— 已經發過的會自動略過，不會重複。
		</p>
	</div>

	<div class="tip">
		<span class="tip-title">綠界：只有信用卡會自動發幣</span>
		<p>
			綠界的訂單明細裡，<b>只有信用卡訂單會顯示付款日期</b>；超商取貨付款即使「已出貨」，
			報表上也看不出買家有沒有到門市付錢（發票、收據欄位也都是空的）。
			所以系統只把<b>信用卡</b>的訂單當成已付款 —— 待出貨或已出貨都算。
		</p>
		<p>
			<strong>超商取貨付款的買家要人工處理</strong>：確認他已經取件付款之後，
			在預覽表格那一列按「開兌換券」，用訂單留言把券碼發給他。
		</p>
	</div>

	<div class="tip">
		<span class="tip-title">狗狗幣怎麼算</span>
		<p>
			商品金額 × {fmt(data.rate)}，<b>不含運費</b>。兩個平台的「總金額」欄都含運費，系統會自動扣掉（運費是 0 也沒問題）。
			預覽表格的金額上停一下滑鼠，可以看到含運費的實付金額。
		</p>
	</div>

	<div class="tip">
		<span class="tip-title">同一份檔案匯入兩次會怎樣？</span>
		<p>
			<strong>不會重複發幣。</strong>訂單編號在資料庫裡是唯一的，
			第二次匯入時那些訂單會顯示「已發放過」並自動跳過。
			所以<b>不確定上次有沒有匯成功時，直接再匯一次是安全的</b>。
		</p>
	</div>

	<p class="lede" style="margin:16px 0 0;font-size:14px">
		<b>綠界「贊助頁」的匯出檔會被擋下</b>：那是觀眾贊助實況主的紀錄，不是周邊訂單，不能拿來發幣。
		請改匯出綠界商店的「訂單明細」。<br /><br />
		認不出格式的其他檔案，展開「手動指定欄位」，自己填訂單編號、金額、備註在第幾欄（從 0 開始數）。
		<strong>這種模式看不到付款狀態，要先自己把未付款的訂單刪掉再匯。</strong>
	</p>
</div>

