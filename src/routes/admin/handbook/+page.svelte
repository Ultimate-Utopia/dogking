<h2>六、四條原則</h2>
<div class="panel">
	<ul class="rules">
		<li>
			<b>先預覽，再確認。</b>
			發幣之後要收回很麻煩（得用人工調整倒扣，而且觀眾可能已經押出去了）。
			預覽不用錢，多按幾次。
		</li>
		<li>
			<b>不確定就再匯一次。</b>
			重複匯入被資料庫擋著，不會有人拿雙倍。反而是「怕重複而不敢補匯」會漏掉人。
		</li>
		<li>
			<b>你做的每一步都有記錄。</b>
			匯入、發券、人工調整全部寫進後台操作紀錄，含時間與操作者。
			這是保護你 —— 有爭議時查得出來到底發生什麼事。
		</li>
		<li>
			<b>活動當天不要做大批匯入。</b>
			對帳留到賽前完成。比賽進行中後台要忙開盤封盤派彩，
			這時候再插進來一批發幣，容易按錯。
		</li>
	</ul>
</div>

